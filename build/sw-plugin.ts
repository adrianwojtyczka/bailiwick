// Emits the PWA payload: a service worker with a precache manifest of the real
// content-hashed bundle filenames, the web app manifest, and the rasterised
// icons. Generating the worker here (rather than hand-maintaining a file list)
// means the offline cache can never drift out of sync with the build.
import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';
import { renderIcon } from './icons';

const ICON_SIZES = [192, 512] as const;

function iconPath(size: number): string {
  return `assets/icon-${size}.png`;
}

function serviceWorkerSource(cacheName: string, precache: readonly string[]): string {
  // Every URL is relative to the worker's own location, so the same build works
  // from a user site root and from a project subpath such as /bailiwick/.
  return `// Generated by build/sw-plugin.ts — do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const INDEX = new URL('index.html', self.location.href).href;

// The precache is keyed purely by URL. Servers commonly send "Vary: Origin",
// and a module script or stylesheet is fetched with an Origin header that the
// precache request did not carry — so without ignoreVary every asset would miss
// the cache and the game would only work offline as a blank page.
const MATCH = { ignoreSearch: true, ignoreVary: true };

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;

  // Navigations always resolve to the cached shell so the game opens offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      caches.match(INDEX, MATCH).then((cached) => cached || fetch(request)),
    );
    return;
  }

  event.respondWith(
    caches.match(request, MATCH).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok && response.type === 'basic') {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    }),
  );
});
`;
}

function webManifest(): string {
  return JSON.stringify(
    {
      name: 'Bailiwick',
      short_name: 'Bailiwick',
      description:
        'A settlement-building real-time strategy game in the spirit of The Settlers II.',
      start_url: './',
      scope: './',
      display: 'fullscreen',
      orientation: 'any',
      background_color: '#f4e8ce',
      theme_color: '#33261a',
      icons: ICON_SIZES.map((size) => ({
        src: `./${iconPath(size)}`,
        sizes: `${size}x${size}`,
        type: 'image/png',
        purpose: 'any maskable',
      })),
    },
    null,
    2,
  );
}

export function serviceWorker(): Plugin {
  return {
    name: 'bailiwick:pwa',
    apply: 'build',

    generateBundle(_options, bundle) {
      for (const size of ICON_SIZES) {
        this.emitFile({ type: 'asset', fileName: iconPath(size), source: renderIcon(size) });
      }

      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: webManifest() });

      const precache = [
        './',
        './index.html',
        './manifest.webmanifest',
        ...ICON_SIZES.map((size) => `./${iconPath(size)}`),
        ...Object.keys(bundle)
          .filter((fileName) => fileName !== 'index.html')
          .map((fileName) => `./${fileName}`),
      ].sort();

      const cacheName = `bailiwick-${createHash('sha256')
        .update(precache.join('\n'))
        .digest('hex')
        .slice(0, 12)}`;

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource(cacheName, precache),
      });
    },
  };
}
